// Regenerates THIRD_PARTY_NOTICES.md: every npm package that ships with Pomelo (read from node_modules),
// plus the programs and Python packages it runs. Run it after changing dependencies.   node tools/make-notices.js
const fs = require('fs');
const path = require('path');
const checker = require('license-checker-rseidelsohn');

const root = path.join(__dirname, '..');

// Programs started as separate processes. Versions are the ones the tests were run with.
const PROGRAMS = [
  ['Electron', 'MIT (bundles Chromium and Node.js under their own licences)', 'https://www.electronjs.org', 'the app shell'],
  ['LibreOffice', 'MPL-2.0', 'https://www.libreoffice.org', 'optional, installed separately: Office formats and PDF export'],
  ['Pandoc', 'GPL-2.0-or-later', 'https://pandoc.org', 'optional, installed separately: Markdown, HTML, RTF, ODT, EPUB'],
  ['FFmpeg (via ffmpeg-static, gyan.dev "essentials" GPL build)', 'GPL-3.0-or-later', 'https://ffmpeg.org', 'video and audio'],
  ['7-Zip 21.07 (via 7zip-bin, the 7za build without the unRAR code)', 'LGPL-2.1-or-later', 'https://www.7-zip.org', 'zip, 7z and tar archives'],
  ['bsdtar / libarchive (tar.exe shipped with Windows 10 and 11)', 'BSD-2-Clause', 'https://www.libarchive.org', 'reading RAR archives'],
];

// Installed by `npm run setup:pdf` into vendor/pyenv (not part of this repository).
const PYTHON = [
  ['pdf2docx', '0.5.13', 'MIT'], ['PyMuPDF', '1.28.2', 'AGPL-3.0-or-later or Artifex commercial'],
  ['pymupdf4llm', '0.3.4', 'AGPL-3.0-or-later or Artifex commercial'], ['pillow-heif', '1.8.1', 'BSD-3-Clause (wheels bundle libheif LGPL-3.0, libde265 LGPL-3.0 and the x265 encoder GPL-2.0-or-later)'],
  ['Pillow', '13.0.0', 'MIT-CMU'], ['NumPy', '2.5.4', 'BSD-3-Clause and others'], ['opencv-python-headless', '5.0.0.93', 'Apache-2.0'],
  ['fonttools', '4.68.0', 'MIT'], ['python-docx', '1.2.0', 'MIT'], ['lxml', '6.1.3', 'BSD-3-Clause'], ['tabulate', '0.10.0', 'MIT'],
  ['fire', '0.7.1', 'Apache-2.0'], ['termcolor', '3.3.0', 'MIT'], ['typing_extensions', '4.16.0', 'PSF-2.0'],
];

// Not allowed: licences that are not open source or that conflict with AGPL-3.0-or-later.
const FORBIDDEN = /PolyForm|Noncommercial|Commons-Clause|SSPL|BUSL|Proprietary|UNLICENSED|CC-BY-NC/i;

checker.init({ start: root, production: true, excludePrivatePackages: true }, (err, packages) => {
  if (err) throw err;
  const rows = Object.entries(packages)
    .map(([id, p]) => ({ id, licenses: [].concat(p.licenses).join(', '), repo: p.repository || '' }))
    .sort((a, b) => a.id.localeCompare(b.id));

  const bad = rows.filter((r) => FORBIDDEN.test(r.licenses));
  if (bad.length) { console.error('Licence problem:\n' + bad.map((r) => `  ${r.id}: ${r.licenses}`).join('\n')); process.exit(1); }

  const md = [
    '# Third-party notices',
    '',
    'Pomelo is licensed under the [GNU AGPL v3 or later](LICENSE). It builds on the open-source software listed here, each under its own licence. This file is generated by `node tools/make-notices.js`; do not edit it by hand.',
    '',
    '## Programs Pomelo runs',
    '',
    '| Program | Licence | Used for |',
    '| --- | --- | --- |',
    ...PROGRAMS.map(([n, l, url, why]) => `| [${n}](${url}) | ${l} | ${why} |`),
    '',
    'LibreOffice and Pandoc are not distributed with Pomelo; they are detected if you install them. The others are installed through npm or `npm run setup:pdf`.',
    '',
    '## Python packages (optional PDF and HEIC engines)',
    '',
    'Installed by `npm run setup:pdf`. `pymupdf4llm` is pinned to 0.3.4 because later releases depend on `pymupdf-layout`, which is licensed PolyForm Noncommercial or commercial and is therefore not open source.',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...PYTHON.map(([n, v, l]) => `| ${n} | ${v} | ${l} |`),
    '',
    `## npm packages (${rows.length})`,
    '',
    'Everything installed by `npm install --omit=dev`, including transitive dependencies. The full licence text of each package is in its folder under `node_modules` and must travel with any redistributed copy.',
    '',
    '| Package | Licence |',
    '| --- | --- |',
    ...rows.map((r) => `| ${r.repo ? `[${r.id}](${r.repo})` : r.id} | ${r.licenses} |`),
    '',
  ].join('\n');

  fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), md);
  console.log(`THIRD_PARTY_NOTICES.md written: ${rows.length} npm packages, ${PROGRAMS.length} programs, ${PYTHON.length} Python packages`);
});
